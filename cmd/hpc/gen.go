// hpc gen derives from the capabilities, defined as Go interfaces, what a
// service needs (docs/concepts/modular-architecture.md §5.4): a Go client
// and server adapter per capability (wire_gen.go in its package), OpenAPI
// with JSON Schema for service authors, and TypeScript types for UIs. It
// reads the packages' source with go/types; nothing has to compile but
// their dependencies, so a stale wire_gen.go never stops it.

const genHeader = "Code generated by hpc gen. DO NOT EDIT."

// genFile is the generated adapter file in each capability package.
const genFile = "wire_gen.go"

func genCmd(args []string) error {
	fl := flag.NewFlagSet("gen", flag.ContinueOnError)
	openapi := fl.String("openapi", "docs/services/openapi", "directory for the OpenAPI files (\"\" for none)")
	ts := fl.String("ts", "web/src/sdk/capabilities", "directory for the TypeScript types (\"\" for none)")
	check := fl.Bool("check", false, "only report files that are not up to date")
	if err := fl.Parse(args); err != nil {
		return err
	}
	patterns := fl.Args()
	if len(patterns) == 0 {
		patterns = []string{"./capability/..."}
	}
	pkgs, err := loadCapabilities(patterns)
	if err != nil {
		return err
	}
	files := map[string][]byte{}
	for _, p := range pkgs {
		if len(p.Caps) == 0 {
			continue
		}
		src, err := genGo(p)
		if err != nil {
			return err
		}
		files[filepath.Join(p.Dir, genFile)] = src
		if *openapi != "" {
			for _, c := range p.Caps {
				b, err := genOpenAPI(p, c)
				if err != nil {
					return err
				}
				files[filepath.Join(*openapi, c.FullName()+".json")] = b
			}
		}
		if *ts != "" {
			files[filepath.Join(*ts, p.Name+".ts")] = genTS(p)
		}
	}
	var names []string
	for n := range files {
		names = append(names, n)
	}
	sort.Strings(names)
	var stale []string
	for _, n := range names {
		old, _ := os.ReadFile(n)
		if bytes.Equal(old, files[n]) {
			continue
		}
		if *check {
			stale = append(stale, n)
			continue
		}
		if err := os.MkdirAll(filepath.Dir(n), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(n, files[n], 0o644); err != nil {
			return err
		}
		fmt.Println("wrote", n)
	}
	if len(stale) > 0 {
		return fmt.Errorf("not up to date, run hpc gen:\n  %s", strings.Join(stale, "\n  "))
	}
	return nil
}

// genPkg is a capability package.
type genPkg struct {
	Path, Name, Dir string
	Pkg             *types.Package
	Caps            []*genCap
	Errors          []genErr
	docs            map[string]string // "Type", "Type.Field", "Iface.Method"
	order           map[string]int    // "Iface.Method" → position in the source
}

// genCap is one capability: NewCapability[T](name, major, Optional[U]()…).
type genCap struct {
	Var      string // PublisherV1
	Name     string // social.publisher
	Major    int
	Iface    *types.TypeName
	Required []*genOp
	Optional []*genOpt
}

// FullName is "social.publisher.v1", for file names.
func (c *genCap) FullName() string { return fmt.Sprintf("%s.v%d", c.Name, c.Major) }

// Wire is "social.publisher/v1".
func (c *genCap) Wire() string { return fmt.Sprintf("%s/v%d", c.Name, c.Major) }

// genOpt is an interface of optional operations.
type genOpt struct {
	Iface *types.TypeName
	Ops   []*genOp
}

// genOp is one method.
type genOp struct {
	Method string // ResolveMention
	Name   string // resolveMention
	Doc    string
	Params []genParam // without the context
	Result types.Type // nil when the method returns only an error
	// Raw is the index of the []byte parameter, or -1.
	Raw       int
	RawResult bool
	// Itself: the body is the only argument itself (a struct).
	Itself bool
}

type genParam struct {
	Name  string // profileURL
	Field string // ProfileURL
	JSON  string // profileUrl
	Type  types.Type
}

type genErr struct{ Var, Code string }

// reserved are names the generated methods use themselves.
var reserved = map[string]bool{"ctx": true, "x": true, "a": true, "in": true, "v": true, "o": true, "out": true, "res": true, "err": true, "t0": true, "wire": true, "time": true, "context": true}

// listedPkg is what go list reports.
type listedPkg struct {
	ImportPath string
	Name       string
	Dir        string
	GoFiles    []string
	Export     string
	DepOnly    bool
	Standard   bool
}

func loadCapabilities(patterns []string) ([]*genPkg, error) {
	cmd := exec.Command("go", append([]string{"list", "-e", "-export", "-deps", "-json"}, patterns...)...)
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("go list: %v\n%s", err, stderr.String())
	}
	exports := map[string]string{}
	var targets []listedPkg
	dec := json.NewDecoder(bytes.NewReader(out))
	for {
		var lp listedPkg
		if err := dec.Decode(&lp); err == io.EOF {
			break
		} else if err != nil {
			return nil, err
		}
		exports[lp.ImportPath] = lp.Export
		if !lp.DepOnly && !lp.Standard {
			targets = append(targets, lp)
		}
	}
	fset := token.NewFileSet()
	imp := importer.ForCompiler(fset, "gc", func(path string) (io.ReadCloser, error) {
		f := exports[path]
		if f == "" {
			return nil, fmt.Errorf("no export data for %s", path)
		}
		return os.Open(f)
	})
	var pkgs []*genPkg
	for _, lp := range targets {
		p, err := loadPkg(fset, imp, lp)
		if err != nil {
			return nil, err
		}
		pkgs = append(pkgs, p)
	}
	return pkgs, nil
}

func loadPkg(fset *token.FileSet, imp types.Importer, lp listedPkg) (*genPkg, error) {
	var files []*ast.File
	for _, name := range lp.GoFiles {
		if strings.HasSuffix(name, "_gen.go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(lp.Dir, name), nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		files = append(files, f)
	}
	info := &types.Info{Types: map[ast.Expr]types.TypeAndValue{}, Uses: map[*ast.Ident]types.Object{}, Defs: map[*ast.Ident]types.Object{}}
	conf := types.Config{Importer: imp}
	pkg, err := conf.Check(lp.ImportPath, fset, files, info)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", lp.ImportPath, err)
	}
	p := &genPkg{Path: lp.ImportPath, Name: lp.Name, Dir: lp.Dir, Pkg: pkg, docs: map[string]string{}, order: map[string]int{}}
	var decls []*ast.ValueSpec
	local := map[*ast.ValueSpec]bool{}
	for _, f := range files {
		for _, d := range f.Decls {
			gd, ok := d.(*ast.GenDecl)
			if !ok {
				continue
			}
			for _, s := range gd.Specs {
				switch s := s.(type) {
				case *ast.TypeSpec:
					p.collectDocs(gd, s)
				case *ast.ValueSpec:
					if gd.Tok == token.VAR {
						decls = append(decls, s)
						if hasDirective(gd.Doc, "hpc:local") || hasDirective(s.Doc, "hpc:local") {
							local[s] = true
						}
					}
				}
			}
		}
	}
	errType := types.Universe.Lookup("error").Type()
	for _, s := range decls {
		for i, name := range s.Names {
			obj := info.Defs[name]
			if obj == nil || !obj.Exported() {
				continue
			}
			if strings.HasPrefix(name.Name, "Err") && types.Identical(obj.Type(), errType) {
				p.Errors = append(p.Errors, genErr{Var: name.Name, Code: snake(strings.TrimPrefix(name.Name, "Err"))})
				continue
			}
			if i >= len(s.Values) || local[s] {
				continue
			}
			c, err := p.capOf(name.Name, s.Values[i], info)
			if err != nil {
				return nil, fmt.Errorf("%s.%s: %w", p.Name, name.Name, err)
			}
			if c != nil {
				p.Caps = append(p.Caps, c)
			}
		}
	}
	sort.Slice(p.Errors, func(i, j int) bool { return p.Errors[i].Code < p.Errors[j].Code })
	return p, nil
}

func hasDirective(g *ast.CommentGroup, d string) bool {
	if g == nil {
		return false
	}
	for _, c := range g.List {
		if strings.TrimSpace(strings.TrimPrefix(c.Text, "//")) == d {
			return true
		}
	}
	return false
}

func (p *genPkg) collectDocs(gd *ast.GenDecl, s *ast.TypeSpec) {
	doc := s.Doc
	if doc == nil && len(gd.Specs) == 1 {
		doc = gd.Doc
	}
	p.docs[s.Name.Name] = docText(doc)
	switch t := s.Type.(type) {
	case *ast.StructType:
		for _, f := range t.Fields.List {
			d := docText(f.Doc)
			if d == "" {
				d = docText(f.Comment)
			}
			for _, n := range f.Names {
				p.docs[s.Name.Name+"."+n.Name] = d
			}
		}
	case *ast.InterfaceType:
		for i, f := range t.Methods.List {
			for _, n := range f.Names {
				p.docs[s.Name.Name+"."+n.Name] = docText(f.Doc)
				p.order[s.Name.Name+"."+n.Name] = i
			}
		}
	}
}

func docText(g *ast.CommentGroup) string {
	if g == nil {
		return ""
	}
	var lines []string
	for _, l := range strings.Split(strings.TrimSpace(g.Text()), "\n") {
		if strings.HasPrefix(strings.TrimSpace(l), "hpc:") {
			continue
		}
		lines = append(lines, l)
	}
	return strings.TrimSpace(strings.Join(lines, "\n"))
}

// capOf recognises companion.NewCapability[T]("name", major, companion.Optional[U]()…).
func (p *genPkg) capOf(varName string, e ast.Expr, info *types.Info) (*genCap, error) {
	call, ok := e.(*ast.CallExpr)
	if !ok {
		return nil, nil
	}
	ix, ok := call.Fun.(*ast.IndexExpr)
	if !ok || !isCompanionFunc(ix.X, "NewCapability", info) {
		return nil, nil
	}
	if len(call.Args) < 2 {
		return nil, errors.New("NewCapability needs a name and a major version")
	}
	nameV, majorV := info.Types[call.Args[0]].Value, info.Types[call.Args[1]].Value
	if nameV == nil || majorV == nil {
		return nil, errors.New("name and major version must be constants")
	}
	c := &genCap{Var: varName, Name: strings.Trim(nameV.ExactString(), `"`)}
	fmt.Sscan(majorV.ExactString(), &c.Major)
	var err error
	if c.Iface, err = ifaceOf(info.Types[ix.Index].Type); err != nil {
		return nil, err
	}
	if c.Required, err = p.opsOf(c.Iface); err != nil {
		return nil, err
	}
	for _, a := range call.Args[2:] {
		oc, ok := a.(*ast.CallExpr)
		oix, ok2 := oc.Fun.(*ast.IndexExpr)
		if !ok || !ok2 || !isCompanionFunc(oix.X, "Optional", info) {
			return nil, errors.New("optional operations are named with companion.Optional[T]()")
		}
		opt := &genOpt{}
		if opt.Iface, err = ifaceOf(info.Types[oix.Index].Type); err != nil {
			return nil, err
		}
		if opt.Ops, err = p.opsOf(opt.Iface); err != nil {
			return nil, err
		}
		c.Optional = append(c.Optional, opt)
	}
	if len(c.Optional) > 4 {
		return nil, errors.New("at most four optional interfaces")
	}
	return c, nil
}

func isCompanionFunc(e ast.Expr, name string, info *types.Info) bool {
	sel, ok := e.(*ast.SelectorExpr)
	if !ok || sel.Sel.Name != name {
		return false
	}
	obj := info.Uses[sel.Sel]
	return obj != nil && obj.Pkg() != nil && obj.Pkg().Path() == corePath+"/companion"
}

func ifaceOf(t types.Type) (*types.TypeName, error) {
	n, ok := t.(*types.Named)
	if !ok {
		return nil, fmt.Errorf("%s is not a named interface", t)
	}
	if _, ok := n.Underlying().(*types.Interface); !ok {
		return nil, fmt.Errorf("%s is not an interface", t)
	}
	return n.Obj(), nil
}

func (p *genPkg) opsOf(tn *types.TypeName) ([]*genOp, error) {
	it := tn.Type().Underlying().(*types.Interface)
	var ops []*genOp
	for i := 0; i < it.NumMethods(); i++ {
		m := it.Method(i)
		sig := m.Type().(*types.Signature)
		op := &genOp{Method: m.Name(), Name: lowerFirst(m.Name()), Doc: p.docs[tn.Name()+"."+m.Name()], Raw: -1}
		where := fmt.Sprintf("%s.%s", tn.Name(), m.Name())
		ps := sig.Params()
		if ps.Len() == 0 || ps.At(0).Type().String() != "context.Context" {
			return nil, fmt.Errorf("%s: the first parameter must be a context.Context", where)
		}
		for j := 1; j < ps.Len(); j++ {
			v := ps.At(j)
			if v.Name() == "" || v.Name() == "_" {
				return nil, fmt.Errorf("%s: parameters need names, they are the JSON keys", where)
			}
			if reserved[v.Name()] {
				return nil, fmt.Errorf("%s: the generated code uses the name %q, call the parameter differently", where, v.Name())
			}
			if isBytes(v.Type()) {
				if op.Raw >= 0 {
					return nil, fmt.Errorf("%s: at most one []byte parameter", where)
				}
				op.Raw = j - 1
			} else if err := checkWire(v.Type(), map[types.Type]bool{}); err != nil {
				return nil, fmt.Errorf("%s: %s: %w", where, v.Name(), err)
			}
			op.Params = append(op.Params, genParam{Name: v.Name(), Field: upperFirst(v.Name()), JSON: jsonKey(v.Name()), Type: v.Type()})
		}
		rs := sig.Results()
		if rs.Len() == 0 || rs.Len() > 2 || rs.At(rs.Len()-1).Type().String() != "error" {
			return nil, fmt.Errorf("%s: must return (T, error) or error", where)
		}
		if rs.Len() == 2 {
			op.Result = rs.At(0).Type()
			if isBytes(op.Result) {
				op.RawResult = true
			} else if err := checkWire(op.Result, map[types.Type]bool{}); err != nil {
				return nil, fmt.Errorf("%s: result: %w", where, err)
			}
		}
		if op.Raw < 0 && len(op.Params) == 1 && isStruct(op.Params[0].Type) {
			op.Itself = true
		}
		ops = append(ops, op)
	}
	// Source order, as the interface declares them.
	sort.SliceStable(ops, func(i, j int) bool {
		return p.order[tn.Name()+"."+ops[i].Method] < p.order[tn.Name()+"."+ops[j].Method]
	})
	return ops, nil
}

func isBytes(t types.Type) bool {
	s, ok := t.Underlying().(*types.Slice)
	if !ok {
		return false
	}
	b, ok := s.Elem().Underlying().(*types.Basic)
	return ok && b.Kind() == types.Byte
}

func isTime(t types.Type) bool {
	n, ok := t.(*types.Named)
	return ok && n.Obj().Pkg() != nil && n.Obj().Pkg().Path() == "time" && n.Obj().Name() == "Time"
}

func isRawJSON(t types.Type) bool {
	n, ok := t.(*types.Named)
	return ok && n.Obj().Pkg() != nil && n.Obj().Pkg().Path() == "encoding/json" && n.Obj().Name() == "RawMessage"
}

func isStruct(t types.Type) bool {
	if isTime(t) {
		return false
	}
	_, ok := t.Underlying().(*types.Struct)
	return ok
}

// checkWire refuses types that cannot travel as JSON: channels, funcs,
// interfaces other than any, and []byte (binary data never travels in
// JSON, §5.4).
func checkWire(t types.Type, seen map[types.Type]bool) error {
	if seen[t] || isTime(t) || isRawJSON(t) {
		return nil
	}
	seen[t] = true
	switch u := t.Underlying().(type) {
	case *types.Basic:
		switch u.Kind() {
		case types.Complex64, types.Complex128, types.UnsafePointer, types.Uintptr:
			return fmt.Errorf("%s cannot travel as JSON", t)
		}
		return nil
	case *types.Pointer:
		return checkWire(u.Elem(), seen)
	case *types.Slice:
		if isBytes(t) {
			return errors.New("[]byte inside JSON: binary data travels as a raw body or a blob URL")
		}
		return checkWire(u.Elem(), seen)
	case *types.Array:
		return checkWire(u.Elem(), seen)
	case *types.Map:
		if b, ok := u.Key().Underlying().(*types.Basic); !ok || b.Info()&types.IsString == 0 {
			return fmt.Errorf("%s: map keys must be strings", t)
		}
		return checkWire(u.Elem(), seen)
	case *types.Struct:
		for i := 0; i < u.NumFields(); i++ {
			f := u.Field(i)
			if !f.Exported() || jsonTag(u.Tag(i)) == "-" {
				continue
			}
			if err := checkWire(f.Type(), seen); err != nil {
				return fmt.Errorf("%s: %w", f.Name(), err)
			}
		}
		return nil
	case *types.Interface:
		if u.Empty() {
			return nil
		}
	}
	return fmt.Errorf("%s cannot travel as JSON", t)
}

// field is a struct field as encoding/json sees it.
type field struct {
	Name      string // JSON key
	GoName    string
	Owner     string // the named struct declaring it, for docs
	Type      types.Type
	OmitEmpty bool
}

// jsonFields lists a struct's fields as encoding/json encodes them,
// embedded structs flattened.
func jsonFields(t types.Type) []field {
	owner := ""
	if n, ok := t.(*types.Named); ok {
		owner = n.Obj().Name()
	}
	st := t.Underlying().(*types.Struct)
	var out []field
	for i := 0; i < st.NumFields(); i++ {
		f := st.Field(i)
		tag := jsonTag(st.Tag(i))
		if tag == "-" {
			continue
		}
		name, opts, _ := strings.Cut(tag, ",")
		if f.Embedded() && name == "" {
			et := f.Type()
			if p, ok := et.(*types.Pointer); ok {
				et = p.Elem()
			}
			if isStruct(et) {
				out = append(out, jsonFields(et)...)
				continue
			}
		}
		if !f.Exported() {
			continue
		}
		if name == "" {
			name = f.Name()
		}
		out = append(out, field{Name: name, GoName: f.Name(), Owner: owner, Type: f.Type(), OmitEmpty: strings.Contains(opts, "omitempty")})
	}
	return out
}

func jsonTag(tag string) string {
	for tag != "" {
		key, rest, ok := strings.Cut(tag, ":")
		if !ok {
			return ""
		}
		key = strings.TrimSpace(key)
		if len(rest) == 0 || rest[0] != '"' {
			return ""
		}
		end := strings.Index(rest[1:], `"`)
		if end < 0 {
			return ""
		}
		val := rest[1 : end+1]
		if key == "json" {
			return val
		}
		tag = rest[end+2:]
	}
	return ""
}

func lowerFirst(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	r[0] = unicode.ToLower(r[0])
	return string(r)
}

func upperFirst(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}

// words splits an identifier at case changes, keeping acronyms together:
// "profileURL" → profile, URL; "NotAProfile" → Not, A, Profile.
func words(s string) []string {
	r := []rune(s)
	var out []string
	start := 0
	for i := 1; i < len(r); i++ {
		lowerToUpper := unicode.IsLower(r[i-1]) && unicode.IsUpper(r[i])
		acronymEnd := i+1 < len(r) && unicode.IsUpper(r[i-1]) && unicode.IsUpper(r[i]) && unicode.IsLower(r[i+1])
		if lowerToUpper || acronymEnd {
			out = append(out, string(r[start:i]))
			start = i
		}
	}
	return append(out, string(r[start:]))
}

// jsonKey is the wire name of a parameter: "profileURL" → "profileUrl".
func jsonKey(s string) string {
	ws := words(s)
	for i, w := range ws {
		w = strings.ToLower(w)
		if i > 0 {
			w = upperFirst(w)
		}
		ws[i] = w
	}
	return strings.Join(ws, "")
}

// snake is an error code: "NotAProfile" → "not_a_profile".
func snake(s string) string {
	ws := words(s)
	for i := range ws {
		ws[i] = strings.ToLower(ws[i])
	}
	return strings.Join(ws, "_")
}
