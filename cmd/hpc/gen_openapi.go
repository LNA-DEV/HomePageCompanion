package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/types"
	"sort"
	"strings"
)

// genOpenAPI describes one capability as OpenAPI 3.1 with JSON Schema, for
// service authors in any language: what the core sends a provider, and
// what a service sends the core through one of its slots (the same body
// under /core/v1/slots/<slot>/<operation>).
func genOpenAPI(p *genPkg, c *genCap) ([]byte, error) {
	s := &schemas{p: p, defs: map[string]any{}}
	paths := map[string]any{}
	add := func(o *genOp, optional bool) {
		post := map[string]any{
			"operationId": o.Name,
			"parameters": []any{map[string]any{
				"name": "Companion-Instance", "in": "header", "schema": map[string]any{"type": "string"},
				"description": "The provider's instance the call is for (\"main\").",
			}},
			"responses": map[string]any{"default": map[string]any{"$ref": "#/components/responses/Error"}},
		}
		if o.Doc != "" {
			post["summary"], post["description"] = firstSentence(o.Doc), o.Doc
		}
		if optional {
			post["x-optional"] = true
		}
		switch {
		case o.Raw >= 0:
			post["requestBody"] = map[string]any{"required": true, "content": map[string]any{
				"application/octet-stream": map[string]any{"schema": map[string]any{"type": "string", "contentMediaType": "application/octet-stream"}},
			}}
			if len(o.Params) > 1 {
				post["parameters"] = append(post["parameters"].([]any), map[string]any{
					"name": "args", "in": "query", "required": true,
					"description": "the other arguments, as JSON",
					"content":     map[string]any{"application/json": map[string]any{"schema": s.args(o, true)}},
				})
			}
		case o.Itself:
			post["requestBody"] = map[string]any{"required": true, "content": map[string]any{
				"application/json": map[string]any{"schema": s.of(o.Params[0].Type)},
			}}
		default:
			post["requestBody"] = map[string]any{"required": true, "content": map[string]any{
				"application/json": map[string]any{"schema": s.args(o, false)},
			}}
		}
		ok := map[string]any{"description": "done"}
		switch {
		case o.RawResult:
			ok["content"] = map[string]any{"application/octet-stream": map[string]any{"schema": map[string]any{"type": "string", "contentMediaType": "application/octet-stream"}}}
		case o.Result != nil:
			ok["content"] = map[string]any{"application/json": map[string]any{"schema": s.of(o.Result)}}
		default:
			ok["content"] = map[string]any{"application/json": map[string]any{"schema": map[string]any{"type": "object"}}}
		}
		post["responses"].(map[string]any)["200"] = ok
		paths["/capabilities/"+c.Wire()+"/"+o.Name] = map[string]any{"post": post}
	}
	for _, o := range c.Required {
		add(o, false)
	}
	for _, oi := range c.Optional {
		for _, o := range oi.Ops {
			if o.Doc == "" {
				o.Doc = p.docs[oi.Iface.Name()]
			}
			add(o, true)
		}
	}
	codes := []string{"bad_request", "unsupported", "unavailable", "internal"}
	for _, e := range p.Errors {
		codes = append(codes, e.Code)
	}
	sort.Strings(codes)
	desc := p.docs[c.Iface.Name()]
	if desc == "" {
		desc = c.Wire()
	}
	doc := map[string]any{
		"openapi": "3.1.0",
		"info": map[string]any{
			"title":       c.Wire(),
			"version":     fmt.Sprint(c.Major),
			"description": desc + "\n\nGenerated by hpc gen from " + p.Path + "." + c.Iface.Name() + ". A service offering it answers these paths; requests from the core carry the Companion-Signature header (docs/services/protocol.md).",
		},
		"paths": paths,
		"components": map[string]any{
			"schemas": s.defs,
			"responses": map[string]any{"Error": map[string]any{
				"description": "the operation failed",
				"content": map[string]any{"application/json": map[string]any{"schema": map[string]any{
					"type":     "object",
					"required": []string{"error"},
					"properties": map[string]any{"error": map[string]any{
						"type":     "object",
						"required": []string{"code", "message"},
						"properties": map[string]any{
							"code":    map[string]any{"type": "string", "description": "a known code, or another one", "examples": codes},
							"message": map[string]any{"type": "string"},
							"cause":   map[string]any{"type": "string", "enum": []string{"account", "content", "transient"}, "description": "the provider's own classification"},
							"status":  map[string]any{"type": "integer", "description": "the HTTP status the platform answered"},
						},
					}},
				}}},
			}},
		},
	}
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	if err := enc.Encode(doc); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

func firstSentence(s string) string {
	s = strings.ReplaceAll(s, "\n", " ")
	if i := strings.Index(s, ". "); i >= 0 {
		return s[:i+1]
	}
	return s
}

// schemas collects JSON Schemas of named types under components.
type schemas struct {
	p    *genPkg
	defs map[string]any
}

func (s *schemas) args(o *genOp, skipRaw bool) map[string]any {
	props := map[string]any{}
	var req []string
	for i, a := range o.Params {
		if skipRaw && i == o.Raw {
			continue
		}
		props[a.JSON] = s.of(a.Type)
		req = append(req, a.JSON)
	}
	out := map[string]any{"type": "object", "properties": props}
	if len(req) > 0 {
		out["required"] = req
	}
	return out
}

func (s *schemas) of(t types.Type) map[string]any {
	switch {
	case isTime(t):
		return map[string]any{"type": "string", "format": "date-time"}
	case isRawJSON(t):
		return map[string]any{}
	}
	if n, ok := t.(*types.Named); ok && isStruct(t) {
		name := n.Obj().Name()
		if n.Obj().Pkg() != nil && n.Obj().Pkg().Path() != s.p.Path {
			name = n.Obj().Pkg().Name() + "." + name
		}
		if _, done := s.defs[name]; !done {
			s.defs[name] = map[string]any{} // against recursion
			s.defs[name] = s.object(t)
		}
		return map[string]any{"$ref": "#/components/schemas/" + name}
	}
	switch u := t.Underlying().(type) {
	case *types.Basic:
		switch {
		case u.Info()&types.IsBoolean != 0:
			return map[string]any{"type": "boolean"}
		case u.Info()&types.IsInteger != 0:
			return map[string]any{"type": "integer"}
		case u.Info()&types.IsFloat != 0:
			return map[string]any{"type": "number"}
		case u.Info()&types.IsString != 0:
			return map[string]any{"type": "string"}
		}
	case *types.Pointer:
		return s.of(u.Elem())
	case *types.Slice:
		return map[string]any{"type": "array", "items": s.of(u.Elem())}
	case *types.Array:
		return map[string]any{"type": "array", "items": s.of(u.Elem()), "minItems": u.Len(), "maxItems": u.Len()}
	case *types.Map:
		return map[string]any{"type": "object", "additionalProperties": s.of(u.Elem())}
	case *types.Struct:
		return s.object(t)
	}
	return map[string]any{}
}

func (s *schemas) object(t types.Type) map[string]any {
	props := map[string]any{}
	var req []string
	for _, f := range jsonFields(t) {
		sc := s.of(f.Type)
		if d := s.p.docs[f.Owner+"."+f.GoName]; d != "" {
			if _, isRef := sc["$ref"]; isRef {
				sc = map[string]any{"allOf": []any{sc}, "description": d}
			} else {
				sc["description"] = d
			}
		}
		props[f.Name] = sc
		_, ptr := f.Type.(*types.Pointer)
		if !f.OmitEmpty && !ptr {
			req = append(req, f.Name)
		}
	}
	out := map[string]any{"type": "object", "properties": props}
	if len(req) > 0 {
		out["required"] = req
	}
	if n, ok := t.(*types.Named); ok {
		if d := s.p.docs[n.Obj().Name()]; d != "" {
			out["description"] = d
		}
	}
	return out
}
