// corePath is the core's module; this repository's own modules live under
// it.
const corePath = "github.com/LNA-DEV/HomePageCompanion"

// BuildFile is build.yaml: what is compiled in
// (docs/concepts/modular-architecture.md §5.6).
type BuildFile struct {
	// Core is a version ("v1.4.0", a branch, a commit) or a local
	// directory ("./", "../HomePageCompanion").
	Core string `yaml:"core"`
	// Modules are "path@version", "path" (this repository's modules: the
	// core's version; others: the latest) or "path => ./dir" (local).
	Modules []string `yaml:"modules"`
}

// Module is one entry of build.yaml.
type Module struct {
	Path    string
	Version string // "" for local ones
	Dir     string // absolute, for local ones
}

// ReadBuildFile reads build.yaml; local directories are relative to it.
func ReadBuildFile(path string) (*BuildFile, []Module, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, nil, err
	}
	var bf BuildFile
	if err := yaml.Unmarshal(raw, &bf); err != nil {
		return nil, nil, fmt.Errorf("%s: %w", path, err)
	}
	if strings.TrimSpace(bf.Core) == "" {
		return nil, nil, fmt.Errorf("%s: core is required (a version or a local directory)", path)
	}
	base := filepath.Dir(path)
	if isLocal(bf.Core) {
		abs, err := resolve(base, bf.Core)
		if err != nil {
			return nil, nil, err
		}
		bf.Core = abs
	}
	seen := map[string]bool{}
	var mods []Module
	for _, e := range bf.Modules {
		m, err := parseEntry(e, base)
		if err != nil {
			return nil, nil, fmt.Errorf("%s: %w", path, err)
		}
		if seen[m.Path] {
			return nil, nil, fmt.Errorf("%s: %s is listed twice", path, m.Path)
		}
		seen[m.Path] = true
		mods = append(mods, m)
	}
	if len(mods) == 0 {
		return nil, nil, fmt.Errorf("%s: no modules (at least a database module is needed)", path)
	}
	return &bf, mods, nil
}

// resolve makes a directory of build.yaml absolute; relative ones are
// relative to build.yaml.
func resolve(base, dir string) (string, error) {
	if filepath.IsAbs(dir) {
		return filepath.Clean(dir), nil
	}
	return filepath.Abs(filepath.Join(base, dir))
}

func isLocal(s string) bool {
	return strings.HasPrefix(s, ".") || strings.HasPrefix(s, "/")
}

func parseEntry(e, base string) (Module, error) {
	e = strings.TrimSpace(e)
	if path, dir, ok := strings.Cut(e, "=>"); ok {
		path, dir = strings.TrimSpace(path), strings.TrimSpace(dir)
		if path == "" || dir == "" {
			return Module{}, fmt.Errorf("%q: want \"path => ./dir\"", e)
		}
		abs, err := resolve(base, dir)
		if err != nil {
			return Module{}, err
		}
		return Module{Path: path, Dir: abs}, nil
	}
	path, version, _ := strings.Cut(e, "@")
	if path == "" || strings.ContainsAny(path, " \t") {
		return Module{}, fmt.Errorf("%q is not a module path", e)
	}
	return Module{Path: path, Version: version}, nil
}

// ownModule reports whether path is one of this repository's modules, and
// its directory under the core.
func ownModule(path string) (string, bool) {
	rest, ok := strings.CutPrefix(path, corePath+"/modules/")
	return rest, ok && rest != "" && !strings.Contains(rest, "/")
}

// Plan is what a build writes into its work directory.
type Plan struct {
	GoMod  []byte
	MainGo []byte
	// Get are the "path@version" arguments for go get, for remote modules.
	Get []string
}

// MakePlan writes go.mod and main.go for a build. A local core replaces the
// core module and this repository's modules without a version with its
// directories; a remote one is fetched with go get, and the core module is
// pinned with a replace so every module, whatever placeholder version of
// the core it requires, builds against the same core.
func MakePlan(bf *BuildFile, mods []Module, goVersion string) Plan {
	var p Plan
	var gm bytes.Buffer
	fmt.Fprintf(&gm, "// Generated by hpc build from build.yaml; do not edit.\nmodule companion.local/build\n\ngo %s\n", goVersion)
	type rep struct{ from, to string }
	var reps []rep
	var reqs []string
	local := isLocal(bf.Core)
	if local {
		reqs = append(reqs, corePath)
		reps = append(reps, rep{corePath, bf.Core})
	} else {
		p.Get = append(p.Get, corePath+"@"+bf.Core)
	}
	for _, m := range mods {
		dir, own := ownModule(m.Path)
		switch {
		case m.Dir != "":
			reqs = append(reqs, m.Path)
			reps = append(reps, rep{m.Path, m.Dir})
		case own && m.Version == "" && local:
			reqs = append(reqs, m.Path)
			reps = append(reps, rep{m.Path, filepath.Join(bf.Core, "modules", dir)})
		case own && m.Version == "":
			p.Get = append(p.Get, m.Path+"@"+bf.Core)
		case m.Version == "":
			p.Get = append(p.Get, m.Path+"@latest")
		default:
			p.Get = append(p.Get, m.Path+"@"+m.Version)
		}
	}
	if len(reqs) > 0 {
		gm.WriteString("\nrequire (\n")
		for _, r := range reqs {
			fmt.Fprintf(&gm, "\t%s v0.0.0-00010101000000-000000000000\n", r)
		}
		gm.WriteString(")\n")
	}
	if len(reps) > 0 {
		gm.WriteString("\nreplace (\n")
		for _, r := range reps {
			fmt.Fprintf(&gm, "\t%s => %s\n", r.from, r.to)
		}
		gm.WriteString(")\n")
	}
	p.GoMod = gm.Bytes()

	paths := make([]string, 0, len(mods))
	for _, m := range mods {
		paths = append(paths, m.Path)
	}
	sort.Strings(paths)
	var mg bytes.Buffer
	mg.WriteString(`// Generated by hpc build from build.yaml; do not edit.
package main

import (
	"embed"
	"io/fs"

	"github.com/LNA-DEV/HomePageCompanion/core"
`)
	for _, path := range paths {
		fmt.Fprintf(&mg, "\t_ %q\n", path)
	}
	mg.WriteString(`)

//go:embed all:shell
var shell embed.FS

func main() {
	if sub, err := fs.Sub(shell, "shell"); err == nil {
		if _, err := fs.Stat(sub, "index.html"); err == nil {
			core.SetShell(sub)
		}
	}
	core.Main()
}
`)
	p.MainGo = mg.Bytes()
	return p
}

// BuildOptions steer a build.
type BuildOptions struct {
	File    string // build.yaml
	Out     string // the program
	Work    string // work directory (kept); default: a temporary one
	Shell   string // a built shell to embed; "" builds <core>/web when the core is local
	NoShell bool
	Version string // stamped into the program; default: the core's version or the commit of a local core
	Log     io.Writer
}

func build(o BuildOptions) error {
	log := o.Log
	if log == nil {
		log = os.Stderr
	}
	bf, mods, err := ReadBuildFile(o.File)
	if err != nil {
		return err
	}
	work := o.Work
	if work == "" {
		if work, err = os.MkdirTemp("", "hpc-build-"); err != nil {
			return err
		}
		defer os.RemoveAll(work)
	} else if work, err = filepath.Abs(work); err != nil {
		return err
	}
	out, err := filepath.Abs(o.Out)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(work, 0o755); err != nil {
		return err
	}
	goVersion, err := goVersionOf(bf)
	if err != nil {
		return err
	}
	plan := MakePlan(bf, mods, goVersion)
	if err := os.WriteFile(filepath.Join(work, "go.mod"), plan.GoMod, 0o644); err != nil {
		return err
	}
	os.Remove(filepath.Join(work, "go.sum"))
	if err := os.WriteFile(filepath.Join(work, "main.go"), plan.MainGo, 0o644); err != nil {
		return err
	}
	env := append(os.Environ(), "GOWORK=off", "CGO_ENABLED=1")
	run := func(args ...string) error {
		fmt.Fprintf(log, "hpc: go %s\n", strings.Join(args, " "))
		cmd := exec.Command("go", args...)
		cmd.Dir, cmd.Env, cmd.Stdout, cmd.Stderr = work, env, log, log
		return cmd.Run()
	}

	version := o.Version
	if len(plan.Get) > 0 {
		if err := run(append([]string{"get"}, plan.Get...)...); err != nil {
			return conflict(err)
		}
		// Pin the core: every module builds against the same one.
		v, err := goList(work, env, corePath)
		if err != nil {
			return err
		}
		if err := run("mod", "edit", "-replace", corePath+"="+corePath+"@"+v); err != nil {
			return err
		}
		if version == "" {
			version = strings.TrimPrefix(v, "v")
		}
	}
	if version == "" && isLocal(bf.Core) {
		version = gitVersion(bf.Core)
	}

	// The shell: a built one, or <core>/web of a local core.
	shellDir := filepath.Join(work, "shell")
	os.RemoveAll(shellDir)
	if err := os.MkdirAll(shellDir, 0o755); err != nil {
		return err
	}
	// go:embed wants at least one file; without index.html the companion
	// serves its placeholder.
	if err := os.WriteFile(filepath.Join(shellDir, ".hpc"), []byte("built by hpc\n"), 0o644); err != nil {
		return err
	}
	switch {
	case o.NoShell:
		fmt.Fprintln(log, "hpc: no shell, the companion serves a placeholder")
	case o.Shell != "":
		if err := copyTree(o.Shell, shellDir); err != nil {
			return fmt.Errorf("shell: %w", err)
		}
	case isLocal(bf.Core):
		web := filepath.Join(bf.Core, "web")
		if err := npmBuild(web, log); err != nil {
			return fmt.Errorf("shell: %w (or pass --shell or --no-shell)", err)
		}
		if err := copyTree(filepath.Join(web, "build"), shellDir); err != nil {
			return fmt.Errorf("shell: %w", err)
		}
	default:
		fmt.Fprintln(log, "hpc: remote core: pass --shell with a built shell; serving a placeholder")
	}
	// Module UIs that are local and come with sources are built in place;
	// the module embeds ui/dist itself.
	for _, m := range mods {
		dir := m.Dir
		if d, own := ownModule(m.Path); own && dir == "" && isLocal(bf.Core) && m.Version == "" {
			dir = filepath.Join(bf.Core, "modules", d)
		}
		if dir == "" || o.NoShell {
			continue
		}
		if _, err := os.Stat(filepath.Join(dir, "ui", "package.json")); err == nil {
			if err := npmBuild(filepath.Join(dir, "ui"), log); err != nil {
				return fmt.Errorf("%s ui: %w", m.Path, err)
			}
		}
	}

	if err := run("mod", "tidy"); err != nil {
		return conflict(err)
	}
	args := []string{"build", "-trimpath", "-o", out}
	if version != "" {
		args = append(args, "-ldflags", "-X "+corePath+"/core.linkedVersion="+version)
	}
	if err := run(append(args, ".")...); err != nil {
		return err
	}
	fmt.Fprintf(log, "hpc: built %s (core %s, %d module(s))\n", out, firstNonEmpty(version, bf.Core), len(mods))
	return nil
}

// conflict names the modules when two of them need versions of one library
// that do not go together.
func conflict(err error) error {
	return fmt.Errorf("%w (when two modules need incompatible versions of one library, the build cannot have both; the go output above names them)", err)
}

func goList(dir string, env []string, path string) (string, error) {
	cmd := exec.Command("go", "list", "-m", "-json", path)
	cmd.Dir, cmd.Env = dir, env
	b, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("go list %s: %w", path, err)
	}
	var m struct{ Version string }
	if err := json.Unmarshal(b, &m); err != nil {
		return "", err
	}
	return m.Version, nil
}

// goVersionOf is the go line of the core's go.mod (local), or the
// toolchain's.
func goVersionOf(bf *BuildFile) (string, error) {
	if isLocal(bf.Core) {
		raw, err := os.ReadFile(filepath.Join(bf.Core, "go.mod"))
		if err != nil {
			return "", fmt.Errorf("core: %w", err)
		}
		for _, line := range strings.Split(string(raw), "\n") {
			if v, ok := strings.CutPrefix(strings.TrimSpace(line), "go "); ok {
				return strings.TrimSpace(v), nil
			}
		}
	}
	b, err := exec.Command("go", "env", "GOVERSION").Output()
	if err != nil {
		return "", err
	}
	return strings.TrimPrefix(strings.TrimSpace(string(b)), "go"), nil
}

func gitVersion(dir string) string {
	cmd := exec.Command("git", "describe", "--tags", "--always", "--dirty")
	cmd.Dir = dir
	b, err := cmd.Output()
	if err != nil {
		return ""
	}
	return strings.TrimPrefix(strings.TrimSpace(string(b)), "v")
}

func npmBuild(dir string, log io.Writer) error {
	if _, err := exec.LookPath("npm"); err != nil {
		return errors.New("npm is not installed")
	}
	for _, args := range [][]string{{"ci"}, {"run", "build"}} {
		fmt.Fprintf(log, "hpc: npm %s (%s)\n", strings.Join(args, " "), dir)
		cmd := exec.Command("npm", args...)
		cmd.Dir, cmd.Stdout, cmd.Stderr = dir, log, log
		if err := cmd.Run(); err != nil {
			return err
		}
	}
	return nil
}

func copyTree(src, dst string) error {
	return filepath.WalkDir(src, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(src, p)
		target := filepath.Join(dst, rel)
		if d.IsDir() {
			return os.MkdirAll(target, 0o755)
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		return os.WriteFile(target, b, 0o644)
	})
}

func firstNonEmpty(a, b string) string {
	if a != "" {
		return a
	}
	return b
}

func buildCmd(args []string) error {
	fl := flag.NewFlagSet("build", flag.ContinueOnError)
	var o BuildOptions
	fl.StringVar(&o.File, "f", "build.yaml", "the build file")
	fl.StringVar(&o.Out, "o", "companion", "the program to write")
	fl.StringVar(&o.Work, "work", "", "work directory to keep (default: a temporary one)")
	fl.StringVar(&o.Shell, "shell", "", "a built admin shell to embed (default: build <core>/web of a local core)")
	fl.BoolVar(&o.NoShell, "no-shell", false, "embed no shell")
	fl.StringVar(&o.Version, "version", "", "the version to stamp (default: the core's)")
	if err := fl.Parse(args); err != nil {
		return err
	}
	return build(o)
}
